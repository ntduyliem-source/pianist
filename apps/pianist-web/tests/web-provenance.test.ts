import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const proof = createRequire(import.meta.url)('../../../buildscripts/pianist/web_provenance.cjs');

function fixture(t: test.TestContext) {
  const parent = fs.realpathSync(os.tmpdir());
  const root = fs.mkdtempSync(path.join(parent, 'pianist-web-provenance-'));
  t.after(() => {
    const resolved = fs.realpathSync(root);
    assert.equal(path.dirname(resolved), parent);
    assert(path.basename(resolved).startsWith('pianist-web-provenance-'));
    fs.rmSync(resolved, { recursive: true, force: true });
  });
  const write = (name: string, value: string | Buffer) => {
    const file = path.join(root, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, value);
    return file;
  };
  const git = (...args: string[]) => execFileSync('git', args, { cwd: root, stdio: 'pipe' });
  const site = path.join(root, 'build.artifacts');
  for (const name of proof.SOURCE_FILES) write(name, name);
  write('apps/pianist-web/src/main.tsx', 'actual app code');
  write('apps/pianist-web/patches/piano.patch', 'actual runtime dependency patch');
  write('packages/practice-engine-v2/engine.ts', 'actual runtime package');
  for (const entry of proof.STATIC) {
    const value = entry.configure ? "const audio = '{{MUSE_MODULE_AUDIO_WORKER}}';" : entry.source;
    write(entry.source, value);
    write('build.artifacts/' + entry.path, value.replaceAll('{{MUSE_MODULE_AUDIO_WORKER}}', 'OFF'));
  }
  write('src/web/appjs/install.js', 'copy glue');
  write('.gitignore', 'build.artifacts/\n.env.local\nignored.ts\n');
  git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  const commit = () => { git('add', '.'); git('commit', '-qm', 'fixture'); };
  commit();
  const build = () => {
    const before = proof.begin(root, site);
    for (const name of proof.REQUIRED_OUTPUTS) write('build.artifacts/' + name, name);
    write('build.artifacts/app/assets/worker-abcd.js', 'worker');
    write('build.artifacts/app/pianist.js.map', 'not published');
    return proof.complete(root, site, before);
  };
  return { root, site, write, commit, build };
}

test('frontend proof allows a native-only commit but rejects changed bundle source/lock/runtime inputs', t => {
  const { root, site, write, commit, build } = fixture(t);
  build(); const original = proof.verify(root, site, true);
  write('packages/score-formats/python/__pycache__/converter.cpython-311.pyc', 'generated by Python oracle');
  assert.deepEqual(proof.verify(root, site, true), original, 'oracle bytecode is not a Vite source input');
  write('src/web/appjs/webapi.cpp', 'native change'); commit();
  assert.deepEqual(proof.verify(root, site, true), original);
  for (const name of ['apps/pianist-web/src/main.tsx', 'apps/pianist-web/package-lock.json',
    'apps/pianist-web/vite.config.ts', 'apps/pianist-web/patches/piano.patch',
    'packages/practice-engine-v2/engine.ts', 'third_party/score-format-sources/manifest.json',
    'scores/grades/definition.json', 'scores/curriculum/length-buckets.v2.json', 'scores/curriculum/grades.v2.json']) {
    const file = path.join(root, name), saved = fs.readFileSync(file);
    write(name, 'changed since bundle build');
    assert.throws(() => proof.verify(root, site), /Stale frontend inputs/, name);
    fs.writeFileSync(file, saved);
  }
  write('apps/pianist-web/src/new.ts', 'new runtime module');
  assert.throws(() => proof.verify(root, site), /Stale frontend inputs/);
});

test('a changed input during build or changed/missing/extra shipped output cannot be certified', t => {
  const { root, site, write, build } = fixture(t);
  build();
  const before = proof.begin(root, site);
  write('apps/pianist-web/src/main.tsx', 'changed while Vite runs');
  assert.throws(() => proof.complete(root, site, before), /changed during build/);
  assert(!fs.existsSync(path.join(site, proof.STAMP)), 'begin removes stale proof even when a build fails');
  build();
  write('build.artifacts/app/pianist.js', 'changed bundle after successful build');
  assert.throws(() => proof.verify(root, site), /outputs differ/);
  build();
  write('build.artifacts/app/assets/stale.js', 'unexpected leftover chunk');
  assert.throws(() => proof.verify(root, site), /outputs differ/);
  fs.unlinkSync(path.join(site, 'app/assets/stale.js'));
  fs.unlinkSync(path.join(site, 'app/library-thumbnail.js'));
  assert.throws(() => proof.verify(root, site), /Missing frontend output/);
});

test('copied MuseScore glue/config/HTML must match source; installing glue does not need a Vite rebuild', t => {
  const { root, site, write, commit, build } = fixture(t);
  build(); const original = proof.verify(root, site, true);
  for (const [source, destination] of [
    ['src/web/appjs/distr/muimpl.js', 'distr/muimpl.js'],
    ['src/web/appjs/distr/config.js.in', 'distr/config.js'],
    ['src/web/appjs/viewer/pianist.html', 'pianist.html'],
  ]) {
    const old = fs.readFileSync(path.join(root, source));
    write(source, 'updated source');
    assert.throws(() => proof.verify(root, site), /Stale installed web source/);
    fs.writeFileSync(path.join(root, source), old);
    const output = fs.readFileSync(path.join(site, destination));
    write('build.artifacts/' + destination, 'old deployed file');
    assert.throws(() => proof.verify(root, site), /Stale installed web source/);
    fs.writeFileSync(path.join(site, destination), output);
  }
  write('src/web/appjs/distr/muimpl.js', 'new glue');
  write('build.artifacts/distr/muimpl.js', 'new glue'); commit();
  const installed = proof.verify(root, site, true);
  assert.equal(installed.inputSha256, original.inputSha256);
  assert.notEqual(installed.installedSourcesSha256, original.installedSourcesSha256);
});

test('ignored dotenv/source inputs are hashed without exposing values, and public release rejects them', t => {
  const { root, site, write, build } = fixture(t);
  write('apps/pianist-web/.env.local', 'VITE_SECRET=never-write-this-value-to-a-stamp');
  write('apps/pianist-web/src/ignored.ts', 'ignored code used by the app');
  const stamp = build();
  proof.verify(root, site);
  assert(!JSON.stringify(stamp).includes('never-write-this-value'));
  assert.throws(() => proof.verify(root, site, true), /absent from the Git source archive/);
  write('apps/pianist-web/.env.local', 'VITE_SECRET=changed');
  assert.throws(() => proof.verify(root, site), /Stale frontend inputs/);
});

test('a future Vite module outside declared inputs blocks the build proof', t => {
  const { root, site, write, build } = fixture(t);
  build();
  write('build.artifacts/app/pianist.js.map', JSON.stringify({ sources: ['../../apps/pianist-web/src/main.tsx'] }));
  proof.validateBundleInputs(root, site);
  write('scores/future-runtime.json', '{"new":"bundle input"}');
  write('build.artifacts/app/pianist.js.map', JSON.stringify({ sources: ['../../scores/future-runtime.json'] }));
  assert.throws(() => proof.validateBundleInputs(root, site), /outside the web provenance inputs/);
});
