"""Copy decision methods verbatim into a headless C# host; fail if pins changed."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / 'third_party/practice-sources'


def method(text, signature):
    start = text.index(signature)
    opening = text.index('{', start)
    # These selected methods have balanced comments/strings; lexical skipping also
    # handles interpolation braces without changing a single character of source.
    i, depth = opening, 0
    while i < len(text):
        if text.startswith('//', i):
            i = text.find('\n', i)
            continue
        if text.startswith('/*', i):
            i = text.index('*/', i + 2) + 2
            continue
        if text[i] in ('"', "'", '`'):
            quote = text[i]
            i += 1
            while i < len(text):
                if text[i] == '\\':
                    i += 2
                elif text[i] == quote:
                    i += 1
                    break
                else:
                    i += 1
            continue
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1
    raise ValueError(signature)


def extract():
    manifest = json.loads((VENDOR / 'manifest.json').read_text())
    for source in manifest['sources']:
        for item in source['files']:
            data = (VENDOR / source['name'] / item['path']).read_bytes()
            assert hashlib.sha256(data).hexdigest() == item['sha256'], item['path']
    extracts = []

    def take(path, signature):
        text = (VENDOR / 'osu' / path).read_text(encoding='utf-8-sig')
        value = method(text, signature)
        extracts.append({'source': path, 'signature': signature, 'sha256': hashlib.sha256(value.encode()).hexdigest()})
        return value

    note_path = 'osu.Game.Rulesets.Mania/Objects/Drawables/DrawableNote.cs'
    base_path = 'osu.Game/Rulesets/Objects/Drawables/DrawableHitObject.cs'
    check = take(note_path, 'protected override void CheckForResult(bool userTriggered, double timeOffset)')
    press = take(note_path, 'public virtual bool OnPressed(KeyBindingPressEvent<ManiaAction> e)')
    update = take(base_path, 'protected bool UpdateResult(bool userTriggered)')
    apply = take(base_path, 'protected void ApplyResult<T>(Action<JudgementResult, T> application, T state)')
    score = take('osu.Game/Rulesets/Scoring/ScoreProcessor.cs', 'public virtual int GetBaseScoreForResult(HitResult result)')
    mania_score = take('osu.Game.Rulesets.Mania/Scoring/ManiaScoreProcessor.cs', 'public override int GetBaseScoreForResult(HitResult result)')
    tail_cap = take('osu.Game.Rulesets.Mania/Objects/Drawables/DrawableHoldNoteTail.cs', 'protected override HitResult GetCappedResult(HitResult result)')
    tail_text=(VENDOR/'osu/osu.Game.Rulesets.Mania/Objects/Drawables/DrawableHoldNoteTail.cs').read_text(encoding='utf-8-sig')
    tail_check=tail_text[tail_text.index('protected override void CheckForResult'):tail_text.index('protected override HitResult GetCappedResult')].strip()
    tail_source=(VENDOR/'osu/osu.Game.Rulesets.Mania/Objects/TailNote.cs').read_text(encoding='utf-8-sig')
    tail_constant=re.search(r'public const double RELEASE_WINDOW_LENIENCE = [^;]+;',tail_source)[0]
    text = f'''// Generated by extract-reference-methods.py. Decision method bodies are verbatim upstream.
// Copyright (c) ppy Pty Ltd. MIT; see third_party/practice-sources/osu/LICENCE.
using System.Diagnostics;
using osu.Game.Rulesets.Scoring;
using osu.Game.Rulesets.Objects;
using osu.Game.Rulesets.Judgements;
using osu.Framework.Input.Events;
using osu.Game.Rulesets.Mania;
using osu.Game.Screens.Play;
namespace osu.Game.Rulesets.Scoring {{public class ScoreProcessor {{{score}}}}}
namespace osu.Game.Rulesets.Mania.Scoring {{public class ManiaScoreProcessor:ScoreProcessor {{{mania_score}}}}}
namespace osu.Game.Rulesets.Objects.Drawables {{
  public partial class DrawableHitObject {{
    {update}
    {apply}
  }}
}}
namespace osu.Game.Rulesets.Mania.Objects.Drawables {{
  public static class TailNote {{{tail_constant}}}
  // Standalone tail probe: input is explicit head-hit / body-break state.
  // The complete hold lifecycle is NOT claimed by this probe.
  public class TailProbe : DrawableNote {{
    public class Flag {{public bool IsHit; public bool HasHoldBreak;}}
    public class Parent {{public Flag Head=new();public Flag Body=new();}}
    public Parent HoldNote=new();
    public TailProbe(HitObject hitObject, osu.Game.Rulesets.Objects.Drawables.ManualClock clock):base(hitObject,clock){{}}
    public void Release() => base.UpdateResult(true);
    {tail_check}
    {tail_cap}
  }}
  public partial class DrawableNote {{
    {check}
    protected virtual HitResult GetCappedResult(HitResult result) => result;
    {press}
  }}
}}
'''
    target = ROOT / 'tests/reference-runners/osu/GeneratedMethods.cs'
    target.write_text(text, encoding='utf8')
    (target.parent / 'extractions.json').write_text(json.dumps(extracts, indent=2) + '\n', encoding='utf8')
    print(f'Extracted {len(extracts)} verbatim upstream methods; all vendor hashes verified.')


if __name__ == '__main__':
    extract()
